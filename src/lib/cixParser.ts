// ============================================================================
// Polyboard CIX Parser & Machine Spec
// Post-processor parser for Biesse Rover A (BiesseWorks / bSolid)
// ============================================================================

export interface CixBoring {
  id?: string;
  side: number; // 0=top, 1=bottom, 2=left, 3=right, 4=front, 5=back
  x: number;
  y: number;
  z: number;
  diameter?: number;
  depth: number;
  through?: boolean;
}

export interface CixRoute {
  id?: string;
  tool?: string;
  depth?: number;
  diameter?: number;
  points: Array<{ x: number; y: number; z?: number }>;
}

export interface ParsedCixPart {
  filename: string;
  partName?: string;
  programName?: string;
  material?: string;
  length: number;    // LPX
  width: number;     // LPY
  thickness: number; // LPZ
  borings: CixBoring[];
  routings: CixRoute[];
  rawLinesCount: number;
}

/**
 * Helper to parse key-value attributes from CIX lines like:
 * BEGIN MAINDATA LPX=800 LPY=600 LPZ=18 ...
 * or PARAM,NAME=X,VALUE=100
 */
function extractAttributes(line: string): Record<string, string> {
  const result: Record<string, string> = {};
  // Check for PARAM,NAME=...,VALUE=... pattern first.
  const paramMatches = line.matchAll(/PARAM\s*,\s*NAME\s*=\s*"?([A-Z0-9_]+)"?\s*,\s*VALUE\s*=\s*(?:"([^"]*)"|([^\s,]+))/gi);
  for (const match of paramMatches) {
    const key = match[1].toUpperCase();
    const value = match[2] !== undefined ? match[2] : match[3];
    result[key] = value;
  }

  // Also match general KEY="VALUE" or KEY=VALUE.
  const regex = /([A-Z0-9_]+)\s*=\s*(?:"([^"]*)"|([^\s,]+))/gi;
  let match: RegExpExecArray | null;
  while ((match = regex.exec(line)) !== null) {
    const key = match[1].toUpperCase();
    if (key === "PARAM" || key === "NAME" || key === "VALUE") continue;
    const value = match[2] !== undefined ? match[2] : match[3];
    if (result[key] === undefined) result[key] = value;
  }
  return result;
}

/**
 * Biesse can emit CUSTSTR as a variable, e.g. $B$PART_NAME, rather than the
 * part's actual label. Treat that token as absent so it cannot be mistaken for
 * a real part name during CIX matching or shown as one in the import report.
 */
function getCixPartName(value: string | undefined): string {
  const name = (value || "").trim();
  return name && !/^\$B\$/i.test(name) ? name : "";
}

/** A macro name is either on BEGIN MACRO or on a following NAME= line. */
function getMacroName(line: string, isBeginLine: boolean): string {
  const match = isBeginLine
    ? line.match(/\bBEGIN\s+MACRO\s+NAME\s*=\s*(?:"([^"]*)"|'([^']*)'|([^\s,]+))/i)
    : line.match(/^\s*NAME\s*=\s*(?:"([^"]*)"|'([^']*)'|([^\s,]+))/i);
  return (match?.[1] ?? match?.[2] ?? match?.[3] ?? "").trim().toUpperCase();
}

function processBoringMacro(params: Record<string, string>, currentCount: number): CixBoring {
  const side = parseInt(params["SIDE"] || "0", 10);
  const x = parseFloat(params["X"] || "0");
  const y = parseFloat(params["Y"] || "0");
  const z = parseFloat(params["Z"] || "0");
  const depth = parseFloat(params["DP"] || params["DEPTH"] || "12");
  const diameter = parseFloat(params["DIA"] || params["DIAM"] || "5");
  const throughValue = (params["THR"] || "").toUpperCase();

  return {
    id: params["ID"] || `hole-${currentCount + 1}`,
    side: Number.isNaN(side) ? 0 : side,
    x: Number.isNaN(x) ? 0 : x,
    y: Number.isNaN(y) ? 0 : y,
    z: Number.isNaN(z) ? 0 : z,
    diameter: Number.isNaN(diameter) ? 5 : diameter,
    depth: Number.isNaN(depth) ? 12 : depth,
    through: throughValue === "1" || throughValue === "YES",
  };
}

/**
 * Parses CIX file content generated by Polyboard for Biesse Rover A CNC
 * machines. Both the compact single-line dialect and Biesse's line-oriented
 * blocks are supported (BEGIN MAINDATA / LPX=... / END MAINDATA and BEGIN
 * MACRO / NAME=BV / ... / END MACRO).
 */
export function parseCix(cixContent: string, filename: string = ""): ParsedCixPart {
  const lines = (cixContent || "").replace(/^\uFEFF/, "").split(/\r\n|\r|\n/);

  let length = 0;
  let width = 0;
  let thickness = 18;
  let material = "";
  const programName = filename.replace(/\.(?:cix|cid|txt)$/i, "");
  let partName = "";

  const borings: CixBoring[] = [];
  const routings: CixRoute[] = [];

  let inMainData = false;
  let inMacro = false;
  let currentMacroName = "";
  let currentMacroParams: Record<string, string> = {};
  let currentRoute: CixRoute | null = null;

  const applyMainData = (line: string) => {
    const attrs = extractAttributes(line);
    if (attrs["LPX"] !== undefined) length = parseFloat(attrs["LPX"]) || 0;
    if (attrs["LPY"] !== undefined) width = parseFloat(attrs["LPY"]) || 0;
    if (attrs["LPZ"] !== undefined) thickness = parseFloat(attrs["LPZ"]) || 18;
    if (attrs["MATERIAL"] !== undefined) material = attrs["MATERIAL"];
    if (attrs["CUSTSTR"] !== undefined) partName = getCixPartName(attrs["CUSTSTR"]);
  };

  const finishRoute = () => {
    if (currentRoute && currentRoute.points.length > 0) routings.push(currentRoute);
    currentRoute = null;
  };

  const configureMacro = () => {
    if (currentMacroName === "ROUT" || currentMacroName === "ROUTG") {
      // In CIX files, the ROUT declaration is followed by START_POINT / LINE_EP
      // macros. Keep the route open until another route begins or the file ends.
      finishRoute();
      currentRoute = {
        id: currentMacroParams["ID"] || `route-${routings.length + 1}`,
        tool: currentMacroParams["TNM"] || currentMacroParams["TOOL"],
        diameter: parseFloat(currentMacroParams["DIA"] || "0"),
        depth: parseFloat(currentMacroParams["DP"] || "0"),
        points: [],
      };
    }
  };

  const finishMacro = () => {
    if ((currentMacroName === "ROUT" || currentMacroName === "ROUTG") && currentRoute) {
      currentRoute.id = currentMacroParams["ID"] || currentRoute.id;
      currentRoute.tool = currentMacroParams["TNM"] || currentMacroParams["TOOL"] || currentRoute.tool;
      currentRoute.diameter = parseFloat(currentMacroParams["DIA"] || "0") || currentRoute.diameter;
      currentRoute.depth = parseFloat(currentMacroParams["DP"] || "0") || currentRoute.depth;
    }
    if (currentMacroName === "BG" || currentMacroName === "BORING" || currentMacroName === "B" || currentMacroName === "BV") {
      borings.push(processBoringMacro(currentMacroParams, borings.length));
    } else if (currentMacroName === "START_POINT" && currentRoute) {
      const x = parseFloat(currentMacroParams["X"] || "0");
      const y = parseFloat(currentMacroParams["Y"] || "0");
      const z = parseFloat(currentMacroParams["Z"] || "0");
      currentRoute.points.push({ x, y, z });
    } else if ((currentMacroName === "LINE_EP" || currentMacroName === "ARC_EPP") && currentRoute) {
      const x = parseFloat(currentMacroParams["XE"] || currentMacroParams["X"] || "0");
      const y = parseFloat(currentMacroParams["YE"] || currentMacroParams["Y"] || "0");
      const z = parseFloat(currentMacroParams["ZE"] || currentMacroParams["Z"] || "0");
      currentRoute.points.push({ x, y, z });
    }

    inMacro = false;
    currentMacroName = "";
    currentMacroParams = {};
  };

  for (const line of lines) {
    const rawLine = line.trim();
    if (!rawLine) continue;

    const startsMainData = /\bBEGIN\s+MAINDATA\b/i.test(rawLine);
    const endsMainData = /\bEND\s+MAINDATA\b/i.test(rawLine);
    if (startsMainData || inMainData) {
      applyMainData(rawLine);
      inMainData = !endsMainData;
      continue;
    }

    const startsMacro = /\bBEGIN\s+MACRO\b/i.test(rawLine);
    if (startsMacro) {
      inMacro = true;
      currentMacroName = getMacroName(rawLine, true);
      currentMacroParams = extractAttributes(rawLine);
      configureMacro();
      if (/\bEND\s+MACRO\b/i.test(rawLine)) finishMacro();
      continue;
    }

    if (!inMacro) continue;

    // The macro identifier may be on its own line immediately after BEGIN MACRO.
    if (!currentMacroName) {
      const macroName = getMacroName(rawLine, false);
      if (macroName) {
        currentMacroName = macroName;
        configureMacro();
      }
    }

    if (/\bEND\s+MACRO\b/i.test(rawLine)) {
      // A few post-processors put the last attributes on the closing line.
      Object.assign(currentMacroParams, extractAttributes(rawLine));
      finishMacro();
      continue;
    }

    Object.assign(currentMacroParams, extractAttributes(rawLine));
  }

  if (inMacro) finishMacro();
  finishRoute();

  // Fallback dimension guess from boring extents if MAINDATA omitted dimensions.
  if (length === 0 && borings.length > 0) {
    const maxX = Math.max(...borings.map((boring) => boring.x));
    if (maxX > 0) length = Math.ceil((maxX + 50) / 10) * 10;
  }
  if (width === 0 && borings.length > 0) {
    const maxY = Math.max(...borings.map((boring) => boring.y));
    if (maxY > 0) width = Math.ceil((maxY + 50) / 10) * 10;
  }

  return {
    filename,
    // Do not surface a $B$ placeholder as a useful name. Falling back to the
    // filename still gives the matcher a stable identity when CUSTSTR is absent.
    partName: partName || filename.replace(/\.(?:cix|cid|txt)$/i, ""),
    programName,
    material,
    length,
    width,
    thickness,
    borings,
    routings,
    rawLinesCount: lines.length,
  };
}
